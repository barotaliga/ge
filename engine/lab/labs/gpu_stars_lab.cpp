namespace gr = ge::render;
constexpr double kPi = 3.14159265358979323846;

// A star's colour by its B-V, as render/sky.wgsl's `star_tint` gives it, as a display byte.
ge::lab::Rgba tint(double bv, double level) {
  const double t = std::clamp((bv + 0.3) / 1.9, 0.0, 1.0);
  const double r = 0.72 + 0.53 * t, g = 0.86 + 0.12 * ge::core::libm::sin(t * kPi),
               b = 1.3 - 0.62 * t;
  auto byte = [&](double c) {
    return static_cast<uint8_t>(std::clamp(c * level * 200.0, 0.0, 255.0));
  };
  return {byte(r), byte(g), byte(b), 255};
}

std::string generated_file(const std::string& table, size_t count) {
  std::string s =
      "// GENERATED by the `stars` lab (`make lab LAB=stars ARGS=\"--bake=<catalog> --write\"`):\n"
      "// never edit by hand. The stars render/stars.hpp decodes: " +
      std::to_string(count) +
      " stars, brightest first, six bytes\n"
      "// each, base64. Their places, magnitudes and colours are the Bright Star Catalogue's, 5th\n"
      "// revised edition (Hoffleit and Warren, 1991), as the astronomical data centres publish\n"
      "// it free of restriction. One literal a line, so no literal passes a compiler's length "
      "limit.\n"
      "//\n"
      "// ge:summary The real stars' table (generated)\n"
      "// ge:keywords stars star-catalogue generated table\n"
      "// ge:skill render\n"
      "// ge:test tests/render_stars_test.cpp\n"
      "namespace ge::render {\n\n"
      "extern const char* const kStarTable[];\n"
      "const char* const kStarTable[] = {\n";
  constexpr size_t kLine = 92;
  for (size_t i = 0; i < table.size(); i += kLine) {
    s += "    \"" + table.substr(i, kLine) + "\",\n";
  }
  s += "    nullptr,\n};\n\n}  // namespace ge::render\n";
  return s;
}

void bake(ge::lab::Lab& lab, const std::string& path) {
  std::ifstream in(path);
  if (!in) {
    lab.fail("cannot read the catalogue at " + path,
             "Pass --bake= the catalogue's unzipped fixed-width `catalog` file. Skill: render.");
    return;
  }
  std::vector<gr::Star> stars;
  std::string line;
  int lines = 0;
  while (std::getline(in, line)) {
    ++lines;
    gr::Star s;
    if (gr::parse_catalogue_line(line, s)) stars.push_back(s);
  }
  std::stable_sort(stars.begin(), stars.end(),
                   [](const gr::Star& a, const gr::Star& b) { return a.mag < b.mag; });
  lab.metric("bake.lines", lines, "count");
  lab.metric("bake.stars", static_cast<double>(stars.size()), "count");
  const std::string table = gr::encode_stars(stars);
  std::vector<gr::Star> back;
  if (!gr::decode_stars(table, back) || back.size() != stars.size()) {
    lab.fail("the baked table does not decode to the stars it was made from",
             "Check encode_stars and decode_stars in engine/render/stars.cpp. Skill: render.");
    return;
  }
  if (lab.arg_bool("write")) {
    const std::filesystem::path out = "engine/render/star_data.cpp";
    if (!std::filesystem::exists(out.parent_path())) {
      lab.fail("--write must run from the repository's root",
               "cd to the checkout and run the lab again. Skill: labs.");
      return;
    }
    std::ofstream f(out, std::ios::binary);
    f << generated_file(table, stars.size());
    lab.note("wrote " + out.string() + " (" + std::to_string(stars.size()) + " stars)");
  }
}

void run(ge::lab::Lab& lab) {
  if (!lab.arg("bake").empty()) {
    bake(lab, lab.arg("bake"));
    return;
  }
  const std::vector<gr::Star>& stars = gr::star_catalogue();
  lab.metric("stars", static_cast<double>(stars.size()), "count");
  if (stars.empty()) {
    lab.fail("the star table decodes to nothing",
             "Bake it again: make lab LAB=stars ARGS=\"--bake=<catalog> --write\". Skill: render.");
    return;
  }
  lab.metric("brightest", stars.front().mag, "mag");
  for (int m = 1; m <= 6; ++m) {
    const auto n =
        std::count_if(stars.begin(), stars.end(), [m](const gr::Star& s) { return s.mag < m; });
    lab.metric("brighter-than-" + std::to_string(m), static_cast<double>(n), "count");
    if (m == 6 && (n < 4000 || n > 6000)) {
      lab.fail(std::to_string(n) +
                   " stars brighter than the sixth magnitude; the sky has about "
                   "4,900",
               "Check parse_catalogue_line's columns in engine/render/stars.cpp. Skill: render.");
    }
  }
  // The map: what it drops, and that each star's cell is where its direction falls.
  const gr::StarMap map = gr::star_map(stars);
  lab.metric("dropped", map.dropped, "count");
  const size_t width = size_t{6} * gr::kStarCells, layer = width * gr::kStarCells;
  int misplaced = 0;
  double brightest_lost = 99;
  for (const gr::Star& s : stars) {
    double d[3];
    gr::star_direction(s, d);
    const gr::CubeCell c = gr::cube_cell(d);
    const size_t at = static_cast<size_t>(c.row) * width +
                      static_cast<size_t>(c.face) * gr::kStarCells + static_cast<size_t>(c.col);
    bool found = false;
    for (size_t slot = 0; slot < gr::kStarSlots; ++slot) {
      const gr::StarCell& cell = map.cells[slot * layer + at];
      if (std::fabs(cell.mag - s.mag) < 1e-3 && std::fabs(cell.u - c.u) < 1e-4) found = true;
    }
    if (!found && s.mag < 6.5) ++misplaced;
    if (!found) brightest_lost = std::min(brightest_lost, s.mag);
  }
  lab.metric("missing-to-6.5", misplaced, "count");
  lab.metric("brightest-missing", brightest_lost, "mag");
  if (map.dropped > 30 || misplaced > 30 || brightest_lost < 4) {
    lab.fail(std::to_string(map.dropped) + " stars dropped by full cells, " +
                 std::to_string(misplaced) + " to the 6.5th magnitude not in their cell, the " +
                 "brightest of the 4th magnitude or brighter",
             "Give the map more slots or cells (kStarSlots, kStarCells in render/stars.hpp). "
             "Skill: render.");
  }

  // The chart.
  const int w = static_cast<int>(lab.arg_num("width")), h = w / 2;
  ge::lab::Picture pic = ge::lab::create_picture(w, h, {6, 8, 18, 255});
  for (int k = 1; k < 12; ++k) {
    const double x = w * k / 12.0;
    ge::lab::draw_line(pic, x, 0, x, h, {24, 28, 46, 255});
  }
  for (int k = 1; k < 6; ++k) {
    const double y = h * k / 6.0;
    ge::lab::draw_line(pic, 0, y, w, y, {k == 3 ? uint8_t{60} : uint8_t{24}, 28, 46, 255});
  }
  for (auto it = stars.rbegin(); it != stars.rend(); ++it) {
    const gr::Star& s = *it;
    if (s.mag > 6.5) continue;
    const double x = (1 - s.ra / (2 * kPi)) * w, y = (0.5 - s.dec / kPi) * h;
    const double r = std::max(0.5, (6.8 - s.mag) * 0.42) * w / 1024.0;
    const double level = std::clamp(1.25 - 0.12 * s.mag, 0.35, 1.25);
    ge::lab::fill_disc(pic, x, y, r, tint(s.bv, level));
  }
  lab.shot({"chart",
            "THE REAL STARS, WHOLE SKY",
            "The table's stars to the 6.5th magnitude on right ascension (0 h at the right "
            "edge, growing to the left; a line every 2 h) and declination (+90 at the top, the "
            "equator the brighter line), each a disc by its magnitude in its colour by B-V.",
            "the constellations where a sky chart has them: the hunter's belt of three on the "
            "equator at 5.5 h, the plough's seven at 11-14 h and +50 to +60, the southern cross "
            "at 12.5 h and -60; blue-white and orange stars mixed",
            {{"width", lab.arg("width")}, {"stars", std::to_string(stars.size())}}},
           pic);
}

