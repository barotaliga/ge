// LAB `stars`: THE REAL STARS (render/stars.hpp), read and baked. Reading (the default) decodes
// the generated table and cuts the cube map the sky pass reads, and checks them: the count
// brighter than each magnitude (the sky's own: about 15 to the first, 4,900 to the sixth), the
// stars no cell held, and that every star lands back in the cell its direction falls in. It draws
// the whole sky as a chart (right ascension along, growing to the left as the sky is seen from
// below; declination up), each star a disc by its magnitude in its colour, so the constellations
// read at a glance.
//
// BAKING (`--bake=<file>`) is the offline half that writes the table: it reads the bright-star
// catalogue's fixed-width text (the 5th revised edition; its `catalog` file, unzipped), keeps the
// stars with a place and a magnitude, brightest first, and with `--write` (from the repository's
// root) writes render/star_data.cpp. Built only with GE_GPU (the table lives in ge_render).
//
// ge:summary Lab: the real stars' table decoded, checked and charted, and baked off the catalogue
// ge:keywords lab stars star-catalogue bake chart magnitude constellations picture
// ge:skill render labs
