// ge:skill console testing
#include <ctime>
#include <map>
#include <string>

#include "check.hpp"
#include "console/clock_macros.hpp"
#include "console/console.hpp"

using namespace ge::console;

namespace {

void use_files(Console& c, std::map<std::string, std::string>& files) {
  c.set_files(
      [&files](std::string_view name, std::string& text) {
        const auto it = files.find(std::string(name));
        if (it == files.end()) return false;
        text = it->second;
        return true;
      },
      [&files](std::string_view name, std::string_view text) {
        files[std::string(name)] = std::string(text);
        return true;
      });
}

}  // namespace

TEST(echo_keeps_spacing_and_reads_escapes) {
  Console c;
  c.execute("_echo \"a  b\"");
  c.execute("_echo -e \"one\\ntwo\"");
  c.execute("_echo -x hi");
  CHECK(c.output().size() == 5);
  CHECK(c.output()[0] == "a  b");
  CHECK(c.output()[1] == "one");
  CHECK(c.output()[2] == "two");
  CHECK(c.output()[3] == "Unknown option: -x.");
  CHECK(c.output()[4] == "Try '_echo --help' for more information.");
}

TEST(text_runs_before_the_rest) {
  Console c;
  c.append("text echo first; echo second");
  c.run();
  CHECK(c.output().size() == 2 && c.output()[0] == "first" && c.output()[1] == "second");
}

TEST(complete_makes_a_name_sent_to_the_game) {
  Console c;
  c.cvars().add({.name = "fov", .fallback = "90"});
  c.execute("complete; complete fov; complete vote; vote yes");
  CHECK(c.output().size() == 3);
  CHECK(c.output()[0] == "Usage: complete <command>");
  CHECK(c.output()[1] == "fov is already defined as a cvar");
  CHECK(c.output()[2] == "Can't \"vote\", not connected");
}

TEST(setu_and_sets_mark_the_info_and_take_every_word) {
  Console c;
  c.execute("setu team red blue; sets admin me");
  const Cvar* team = c.cvars().find("team");
  const Cvar* admin = c.cvars().find("admin");
  CHECK(team != nullptr && team->value == "red blue" && (team->flags & kUserInfo) != 0);
  CHECK(admin != nullptr && (admin->flags & kServerInfo) != 0);
  c.execute("sets team red");  // the server mark replaces the user one
  CHECK((team->flags & kUserInfo) == 0 && (team->flags & kServerInfo) != 0);
  c.execute("setu x");
  CHECK(c.output().back() == "Usage: setu <variable> <value>");
}

TEST(resetall_returns_every_setting_but_the_read_only) {
  Console c;
  c.cvars().add({.name = "fov", .fallback = "90"});
  c.cvars().add({.name = "version", .fallback = "1", .flags = kReadOnly});
  c.execute("fov 110; resetall");
  CHECK(c.cvars().find("fov")->value == "90");
  CHECK(c.cvars().find("version")->value == "1");
}

TEST(writeconfig_writes_binds_and_archived_by_default) {
  Console c;
  std::map<std::string, std::string> files;
  use_files(c, files);
  c.cvars().add({.name = "fov", .fallback = "90", .flags = kArchive});
  c.cvars().add({.name = "volume", .fallback = "1"});
  c.execute("fov 100; volume 0.5; alias hi \"echo hi\"; writeconfig mine");
  CHECK(c.output().back() == "Wrote mine.cfg.");
  bool found = false;
  for (const auto& [name, text] : files) {
    if (!name.ends_with("mine.cfg")) continue;
    found = true;
    CHECK(text.starts_with("// generated by writeconfig\n"));
    CHECK(text.find("seta fov \"100\"") != std::string::npos);
    CHECK(text.find("volume") == std::string::npos);  // not archived
    CHECK(text.find("alias") == std::string::npos);   // -a not given
  }
  CHECK(found);
  c.execute("writeconfig -m -a all");
  for (const auto& [name, text] : files) {
    if (!name.ends_with("all.cfg")) continue;
    CHECK(text.find("set volume \"0.5\"") != std::string::npos);
    CHECK(text.find("alias \"hi\" \"echo hi\"") != std::string::npos);
  }
  c.execute("writeconfig");
  CHECK(c.output()[c.output().size() - 2] == "Missing filename argument.");
}

TEST(userinfo_lists_the_user_info_settings) {
  Console c;
  c.execute("setu name player; setu skin male/grunt");
  c.execute("userinfo");
  CHECK(c.output().size() >= 3);
  CHECK(c.output()[0] == "User info settings:");
  CHECK(c.output()[1] == "name                 player");
}

TEST(lasterror_prints_the_last_refusal_again) {
  Console c;
  c.execute("lasterror");
  CHECK(c.output().size() == 1 && c.output()[0].empty());
}

TEST(toggle_steps_through_its_values) {
  Console c;
  c.cvars().add({.name = "crosshair", .fallback = "1"});
  c.execute("toggle crosshair 1 2 3; crosshair");
  CHECK(c.cvars().find("crosshair")->value == "2");
  c.execute("toggle crosshair 1 2; toggle crosshair 1 2");
  CHECK(c.cvars().find("crosshair")->value == "2");
  c.execute("crosshair 9; toggle crosshair 1 2");
  CHECK(c.output().back() == "\"crosshair\" is \"9\", can't cycle");
}

TEST(uptime_reads_in_both_forms) {
  CHECK(uptime_short(65) == "01.05");
  CHECK(uptime_short(3600 + 125) == "1:02.05");
  CHECK(uptime_short(86400 + 3600) == "1+1:00.00");
  CHECK(uptime_long(0) == "0 secs");
  CHECK(uptime_long(86400 + 7200 + 5) == "1 day, 2 hours, 5 secs");
}

TEST(clock_macros_read_the_clock_given) {
  Console c;
  std::tm t{};
  t.tm_year = 126;
  t.tm_mon = 10;
  t.tm_mday = 21;
  t.tm_hour = 9;
  t.tm_min = 5;
  add_clock_macros(c, {.local = [t] { return t; }, .uptime_s = [] { return 61.0; }});
  CHECK(c.expand_text("$com_date") == "2026-11-21");
  CHECK(c.expand_text("$com_time") == "09:05");
  CHECK(c.expand_text("$com_uptime") == "01.01");
  c.execute("com_date_format %d/%m");
  CHECK(c.expand_text("$com_date") == "21/11");
  const std::string r = c.expand_text("$random");
  CHECK(r.size() == 1 && r[0] >= '0' && r[0] <= '9');
}
