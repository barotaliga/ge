namespace sh = ge::shooter;

// What an attack fires.
enum class Fire : uint8_t {
  none,
  bolt,     // a blaster bolt, `count` at once
  pellets,  // a shotgun's `count` pellets
  burst,    // one bullet a frame for `burst_min`..`burst_max` s (or a loop)
  club,     // a blow within reach: damage..damage_max, `kick` added to the target's velocity
  grenade,
  rockets,  // `count` rockets, one every 0.2 s (or `count` at once on a loop)
  drain,    // a tongue that holds while the line is clear
  rail,     // a rail at the aim taken `remember` s before the shot
  bfg,      // a ball whose final burst is `damage` strong within `reach`
  guns,     // `count` bullets a shot, aimed `lead` s along the enemy's motion
  sweep,    // a bolt a shot, its yaw sweeping across the enemy
  zap,      // an energy blow wherever the enemy is
  leap,     // a jump at the enemy that hurts what it strikes fast
};

// How a kind decides to attack.
enum class Test : uint8_t {
  usual,   // sequel-monsters.md § Choosing to attack
  hover,   // 0.8 a frame within mid range, not by skill (the hornet)
  rider,   // 0.8 at melee range, 0.4 near, 0.2 mid, not by skill (Jorg and the Makron)
  mutant,  // claws in melee range, else a leap when its test passes
};

// What its death leaves.
enum class End : uint8_t {
  corpse,   // a corpse, or gibs under its gib health
  explode,  // an explosion at once, nothing left
  boss,     // `death_time` s of dying, then eight blasts and the wreck thrown apart
  crash,    // a corpse that explodes on landing (or 15 s on)
  launch,   // a boss's death that brings out the Makron (Jorg)
};

struct Attack {
  Fire fire = Fire::none;
  int damage = 0, damage_max = 0;
  int kick = 0;
  float speed = 0;
  int count = 1;
  float h = 0, v = 0;                     // the spread at 8192, right and up
  float burst_min = 0, burst_max = 0;     // s
  float windup = 0.3f;                    // s before the first shot
  float every = 0;                        // s between shots on a loop; 0 the older rules by fire
  float loop = 0;                         // s a loop lasts
  int shots = 0;                          // shots a loop (0: every one the loop has room for)
  float again = 0;                        // the chance of another loop
  int again_max = 0;                      // loops more at most (0 no limit)
  float again_every = 0, again_loop = 0;  // the later loops' (0: the first's)
  float recover = 0.3f;                   // s after the last shot
  float weight = 1;                       // its share among the kind's ranged attacks
  float closest = 0;                      // it holds its fire nearer than this
  float reach = 0;                        // a ball's burst reach
  float lead = 0;                         // s along the enemy's motion it aims
  float remember = 0;                     // a rail's aim taken this long before the shot
  int follow = -1;                        // the blow that follows a hit (at skill 1 and up)
};

struct Kind {
  const char* classname;
  const char* name;  // the obituary's
  const char* model;
  const char *sight = nullptr, *pain = nullptr, *death = nullptr;
  int skin = 0;
  int health = 0, gib = 0, mass = 0;
  float walk = 50, run = 150;  // units/s
  float close = 0;             // nearer than this the first ranged attack, always
  float death_time = 1;        // s from its death to its end
  float revive_after = 1;      // s from its death until a medic may raise it
  sh::Vec3f mins{-16, -16, -24}, maxs{16, 16, 32};
  Attack melee[2] = {};
  Attack missile[3] = {};
  bool flies = false, swims = false;
  Test test = Test::usual;
  End end = End::corpse;
  bool screen = false;  // a power screen of 100 in front
  bool medic = false;   // raises the dead
  bool prop = false;    // not a monster: a figure that only answers a use
  bool keep = false;    // kept in deathmatch
};

constexpr int kNoGib = -100000;  // a kind that is never thrown apart

constexpr Attack club(int lo, int hi, int kick) {
  Attack a;
  a.fire = Fire::club;
  a.damage = lo;
  a.damage_max = hi;
  a.kick = kick;
  return a;
}

