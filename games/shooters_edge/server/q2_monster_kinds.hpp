// QUAKE II'S MONSTER ROSTER: every kind's numbers as data, read by q2_monsters.cpp. The
// numbers are the clean-room notes' (porting/shooters-edge/q2-monsters.md for the demo's
// roster, q2-monsters-full.md for the full game's); the timings between them are ours, built
// from the notes' frame counts at 0.1 s a frame.
//
// An attack is a wind-up, then shots on a loop (`every` s apart, `shots` of them a loop), then a
// recovery; at a loop's end it goes on with the chance `again` while it still has its mark. A kind
// has up to two blows (at even odds) and three ranged attacks (by `weight`).
//
// ge:summary Quake II's monster roster: health, boxes, speeds, every attack's numbers and timing
// ge:keywords q2 monsters roster monster-kinds attack-timing medic boss super-tank makron
// ge:keywords swimmer flier power-screen cr_monsters remix classic-monsters
// ge:skill shooter
// ge:test tests/shooters_edge_q2_monsters_test.cpp
