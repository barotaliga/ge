// What an attack fires.
enum class Fire : uint8_t {
  none,
  bolt,     // a blaster bolt, `count` at once
  pellets,  // a shotgun's `count` pellets
  burst,    // one bullet a frame for `burst_min`..`burst_max` s (or a loop)
  club,     // a blow within reach: damage..damage_max, `kick` added to the target's velocity
  grenade,
  rockets,  // `count` rockets, one every 0.2 s (or `count` at once on a loop)
  drain,    // a tongue that holds while the line is clear
  rail,     // a rail at the aim taken `remember` s before the shot
  bfg,      // a ball whose final burst is `damage` strong within `reach`
  guns,     // `count` bullets a shot, aimed `lead` s along the enemy's motion
  sweep,    // a bolt a shot, its yaw sweeping across the enemy
  zap,      // an energy blow wherever the enemy is
  leap,     // a jump at the enemy that hurts what it strikes fast
  laser,    // `count` beams a shot (one an eye), re-aimed each frame, burning through bodies
  tongue,   // a strike that pulls its enemy in, within 512 and 30 degrees of level
};

// The missile a `bolt` or `rockets` attack throws: the base game's, or a pack's (q2_combat.hpp's
// SqShot: the ion ripper's disc, the blue bolt, the phalanx's ball, the heat rocket, the spit).
enum class Shot : uint8_t { usual, ripper, blue_bolt, plasma, heat_rocket, spit, green_bolt };

// The words a death by an attack reads: its kind's ("died." in co-op), a laser's ("saw the
// light.") or a bite's ("that's gotta hurt.").
enum class Words : uint8_t { usual, light, hurt };

// How a kind decides to attack.
enum class Test : uint8_t {
  usual,   // q2-monsters.md § Choosing to attack
  hover,   // 0.8 a frame within mid range, not by skill (the hornet)
  rider,   // 0.8 at melee range, 0.4 near, 0.2 mid, not by skill (Jorg and the Makron)
  mutant,  // claws in melee range, else a leap when its test passes
  gekk,    // claws in melee range; on land, else nearly always a spit or a leap; in water, claws
};

// What its death leaves.
enum class End : uint8_t {
  corpse,   // a corpse, or gibs under its gib health
  explode,  // an explosion at once, nothing left
  boss,     // `death_time` s of dying, then eight blasts and the wreck thrown apart
  crash,    // a corpse that explodes on landing (or 15 s on)
  launch,   // a boss's death that brings out the Makron (Jorg)
};

struct Attack {
  Fire fire = Fire::none;
  int damage = 0, damage_max = 0;
  int kick = 0;
  float speed = 0;
  int count = 1;
  float h = 0, v = 0;                     // the spread at 8192, right and up
  float burst_min = 0, burst_max = 0;     // s
  float windup = 0.3f;                    // s before the first shot
  float every = 0;                        // s between shots on a loop; 0 the older rules by fire
  float loop = 0;                         // s a loop lasts
  int shots = 0;                          // shots a loop (0: every one the loop has room for)
  float again = 0;                        // the chance of another loop
  int again_max = 0;                      // loops more at most (0 no limit)
  float again_every = 0, again_loop = 0;  // the later loops' (0: the first's)
  float recover = 0.3f;                   // s after the last shot
  float weight = 1;                       // its share among the kind's ranged attacks
  float closest = 0;                      // it holds its fire nearer than this
  float reach = 0;                        // a ball's burst reach
  float lead = 0;                         // s along the enemy's motion it aims
  float remember = 0;                     // a rail's aim taken this long before the shot
  int follow = -1;                        // the blow that follows a hit (at skill 1 and up)
  int again_skill = 0;                    // the least skill that loops again
  float aim_h = 0, aim_v = 0;             // the soldiers' spread at 8192, once a shot, before h/v
  Shot shot = Shot::usual;                // a bolt's or a rocket's missile
  Words words = Words::usual;             // a death by it
  float farthest = 0;                     // taken only within this (0 any range)
  float rise = 250;                       // a leap's speed up
  int splash = 0;                         // a missile's splash (0 its shot's own)
};

struct Kind {  // NOLINT(clang-analyzer-optin.performance.Padding): rows read by name
  const char* classname;
  const char* name;  // the obituary's
  const char* model;
  const char *sight = nullptr, *pain = nullptr, *death = nullptr;
  int skin = 0;
  int health = 0, gib = 0, mass = 0;
  float walk = 50, run = 150;  // units/s
  float close = 0;             // nearer than this the first ranged attack, always
  float death_time = 1;        // s from its death to its end
  float revive_after = 1;      // s from its death until a medic may raise it
  sh::Vec3f mins{-16, -16, -24}, maxs{16, 16, 32};
  Attack melee[2] = {};
  Attack missile[3] = {};
  bool flies = false, swims = false;
  Test test = Test::usual;
  End end = End::corpse;
  int burst = 0;          // an explosion's harm: this less half the distance, within this + 40
  bool screen = false;    // a power screen of 100 in front
  bool medic = false;     // raises the dead
  bool prop = false;      // not a monster: a figure that only answers a use
  bool keep = false;      // kept in deathmatch
  bool good = false;      // a good guy: never hunts, never counted, never angered
  bool turret = false;    // rides and aims a turret (q2_targets.cpp) instead of walking
  bool by_range = false;  // the tank's choice: blaster or gun near, any of three far
  // Its voice standing (`idle`, an idle's short reach) and walking its path (`search`, one of up
  // to three at even odds, played `search_odds` of the time, at `search_reach`: 1 normal, 2 an
  // idle's, 0 the whole map), on one timer: 15 to 30 s apart. `loop` it carries all along.
  const char* idle = nullptr;
  const char* search[3] = {};
  float search_odds = 1;
  int8_t search_reach = 1;
  const char* loop = nullptr;
  // The rules it belongs to (q2_pack.hpp). A pack's row of a base class name replaces the base
  // row under that pack (`kind_named`).
  Q2Pack pack = Q2Pack::base;
  // A pack's kind built on a base one: the base class whose model frames, pains, deaths, ducks,
  // steps, gibs and muzzle flashes it shares (`looks_like`).
  const char* like = nullptr;
  // A power shield of `shield` points over every direction (a pack's armoured kinds): two thirds
  // of a blow taken, two damage a point, the green shell shown. With `shield_flag`, only when its
  // map sets that spawn flag.
  int shield = 0;
  int shield_flag = 0;
  bool pain_at_3 = false;     // flinches at skill 3 too
  bool green = false;         // bleeds green
  bool heals = false;         // its search and idle heal it 10 to 20
  bool amphibian = false;     // walks on land, swims in water, by where it stands
  bool repairs = false;       // the repair bot: roams, welds, raises the dead with its beam
  const char* chant[3] = {};  // spawn flag 8: it chants (one of three) and looks for no one
  // Ground Zero's bosses' (q2_gz_bosses.cpp): its turn a frame in degrees (0: a walker's 20, a
  // flier's 10), the height a flier keeps over its enemy, lasers pass it by, and shots between it
  // and another monster start no fight.
  float yaw_speed = 0;
  float hover = 35;
  bool laser_proof = false;
  bool ignore_shots = false;
};

// The class whose frames, pains, deaths and flashes kind `k` plays: its base kind's, or its own.
constexpr const char* looks_like(const Kind& k) { return k.like != nullptr ? k.like : k.classname; }

constexpr int kNoGib = -100000;  // a kind that is never thrown apart

constexpr Attack club(int lo, int hi, int kick) {
  Attack a;
  a.fire = Fire::club;
  a.damage = lo;
  a.damage_max = hi;
  a.kick = kick;
  return a;
}

