std::span<const RocketTrick> rocket_tricks(std::string_view name) {
  size_t first = 0, n = 0;
  for (size_t i = 0; i < std::size(kTricks); i++) {
    if (name != kTricks[i].map) continue;
    if (n == 0) first = i;
    n++;
  }
  return {kTricks + first, n};
}

